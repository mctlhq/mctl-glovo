// Command landing-gen writes landing-worker/src/pages.gen.js: the landing
// page of glovo-home, rendered in every language, for the Cloudflare Worker
// that serves https://glovo.mctl.ai/ at the edge. The Go template stays the
// single source; TestGeneratedFileIsCurrent fails when the file is stale.
//
//	go run ./cmd/landing-gen -out landing-worker/src/pages.gen.js
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"

	"github.com/mctlhq/mctl-glovo/internal/config"
	"github.com/mctlhq/mctl-glovo/internal/gateway"
)

func generate() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/landing-gen; DO NOT EDIT.\n\n")
	langs := gateway.LandingLangs()
	for _, kv := range []struct {
		name string
		v    any
	}{{"LANGS", langs}, {"COOKIE", gateway.LandingLangCookie}, {"CSP", gateway.LandingCSP()}} {
		j, err := json.Marshal(kv.v)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "export const %s = %s;\n", kv.name, j)
	}
	b.WriteString("export const PAGES = {\n")
	for _, l := range langs {
		page, err := gateway.RenderLanding(l, config.Resource)
		if err != nil {
			return nil, err
		}
		j, err := json.Marshal(string(page))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "  %s: %s,\n", l, j)
	}
	b.WriteString("};\n")
	return b.Bytes(), nil
}

func main() {
	out := flag.String("out", "landing-worker/src/pages.gen.js", "output file")
	flag.Parse()
	b, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "landing-gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, b, 0o644); err != nil { //nolint:gosec // G306: a public, generated source file
		fmt.Fprintln(os.Stderr, "landing-gen:", err)
		os.Exit(1)
	}
}
